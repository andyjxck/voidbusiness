#!/usr/bin/env node
// Generates the hosted legal pages from the same text the app shows:
//   docs/privacy.html, docs/terms.html  (standalone pages to upload to the website)
//   PRIVACY_POLICY.md, TERMS_OF_USE.md   (repo copies)
// Run: npm run legal:build   (re-run after editing src/data/legalText.js)

const fs = require('fs');
const path = require('path');
const { PRIVACY, TERMS } = require('../src/data/legalText');
const { LEGAL_LAST_UPDATED, APP_NAME, SUPPORT_EMAIL, PRIVACY_POLICY_URL, TERMS_OF_USE_URL } = require('../src/config/legal');

const root = path.join(__dirname, '..');

function esc(s) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function linkify(s) {
  return esc(s)
    .replace(/(https?:\/\/[^\s)]+[^\s).,])/g, '<a href="$1">$1</a>')
    .replace(/([A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,})/g, '<a href="mailto:$1">$1</a>')
    .replace(/\(ico\.org\.uk\)/g, '(<a href="https://ico.org.uk">ico.org.uk</a>)');
}

function bodyToHtml(body) {
  return body.split('\n\n').map((para) => {
    const lines = para.split('\n');
    if (lines.every((l) => l.startsWith('\u2022 '))) {
      return '<ul>\n' + lines.map((l) => `  <li>${linkify(l.slice(2))}</li>`).join('\n') + '\n</ul>';
    }
    if (lines.some((l) => l.startsWith('\u2022 '))) {
      return lines.map((l) => (l.startsWith('\u2022 ') ? `<ul><li>${linkify(l.slice(2))}</li></ul>` : `<p>${linkify(l)}</p>`)).join('\n');
    }
    return `<p>${lines.map(linkify).join('<br>\n')}</p>`;
  }).join('\n');
}

function page(title, sections, otherLabel, otherHref) {
  const body = sections.map((s) => `<section>\n<h2>${esc(s.title)}</h2>\n${bodyToHtml(s.body)}\n</section>`).join('\n\n');
  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)} - ${esc(APP_NAME)}</title>
<style>
  :root { color-scheme: light dark; }
  body { margin: 0; font: 16px/1.6 -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; background: #0b0b0f; color: #e5e7eb; }
  main { max-width: 720px; margin: 0 auto; padding: 40px 20px 64px; }
  h1 { font-size: 30px; line-height: 1.2; margin: 0 0 6px; color: #fff; }
  h2 { font-size: 19px; margin: 32px 0 8px; color: #fbbf24; }
  .updated { color: #9ca3af; font-size: 14px; margin: 0 0 24px; }
  a { color: #fbbf24; }
  ul { padding-left: 22px; margin: 8px 0; }
  li { margin: 4px 0; }
  footer { margin-top: 48px; padding-top: 16px; border-top: 1px solid #27272a; color: #9ca3af; font-size: 14px; }
  @media (prefers-color-scheme: light) {
    body { background: #fff; color: #1f2937; }
    h1 { color: #111827; }
    h2, a { color: #b45309; }
    footer { border-top-color: #e5e7eb; color: #6b7280; }
  }
</style>
</head>
<body>
<main>
<h1>${esc(APP_NAME)} ${esc(title)}</h1>
<p class="updated">Last updated: ${esc(LEGAL_LAST_UPDATED)}</p>

${body}

<footer>
<p><a href="${otherHref}">${esc(otherLabel)}</a> &middot; Contact: <a href="mailto:${SUPPORT_EMAIL}">${SUPPORT_EMAIL}</a></p>
</footer>
</main>
</body>
</html>
`;
}

function markdown(title, sections) {
  const parts = [`# ${APP_NAME} ${title}`, '', `Last updated: ${LEGAL_LAST_UPDATED}`, '',
    '<!-- Generated by scripts/build-legal-pages.js from src/data/legalText.js. Edit that file, then run npm run legal:build. -->', ''];
  for (const s of sections) {
    parts.push(`## ${s.title}`, '', s.body.replace(/^\u2022 /gm, '- '), '');
  }
  return parts.join('\n');
}

fs.mkdirSync(path.join(root, 'docs'), { recursive: true });
fs.writeFileSync(path.join(root, 'docs', 'privacy.html'), page('Privacy Policy', PRIVACY, 'Terms of Use', TERMS_OF_USE_URL));
fs.writeFileSync(path.join(root, 'docs', 'terms.html'), page('Terms of Use', TERMS, 'Privacy Policy', PRIVACY_POLICY_URL));
fs.writeFileSync(path.join(root, 'PRIVACY_POLICY.md'), markdown('Privacy Policy', PRIVACY));
fs.writeFileSync(path.join(root, 'TERMS_OF_USE.md'), markdown('Terms of Use', TERMS));
console.log('Wrote docs/privacy.html, docs/terms.html, PRIVACY_POLICY.md, TERMS_OF_USE.md');
