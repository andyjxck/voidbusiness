// Translate using whole-word matching only (no substring corruption)
function translateWordByWord(value, dict) {
  if (!dict || Object.keys(dict).length === 0) return value;
  // Split into tokens: words vs non-words (spaces, punctuation, placeholders)
  const tokens = value.split(/(\{[^}]+\}|\s+|[^\w-]+)/g).filter(t => t !== '');
  const result = tokens.map(token => {
    // Don't touch placeholders like {v0}, {v1}, etc.
    if (/^\{[^}]+\}$/.test(token)) return token;
    // Don't touch non-word tokens (spaces, punctuation)
    if (!/^[A-Za-z]/.test(token)) return token;
    // Try exact match first
    if (dict[token] !== undefined) return dict[token];
    // Try lowercase match
    if (dict[token.toLowerCase()] !== undefined) return dict[token.toLowerCase()];
    // Try title case match
    const tc = token.charAt(0).toUpperCase() + token.slice(1).toLowerCase();
    if (dict[tc] !== undefined) return dict[tc];
    // No match - keep original
    return token;
  });
  return result.join('');
}

